def cpp_string(text):
    result = '"'
    for byte in text.encode("utf-8"):
        if byte in (34, 63, 92):
            result += "\\" + chr(byte)
        elif 32 <= byte < 127:
            result += chr(byte)
        else:
            result += f"\\{byte:03o}"
    return result + '"'


def length(value):
    return "LV_SIZE_CONTENT" if value[0] == "auto" else f"lv_pct({value[1]})" if value[0] == "percent" else str(value[1])


def styles(obj, node):
    style = node.style
    lines = []

    def put(property, value):
        lines.append(f"  lv_obj_set_style_{property}({obj}, {value}, LV_PART_MAIN | LV_STATE_DEFAULT);")

    put("width", length(style["width"]))
    put("height", length(style["height"]))
    for key, value in [("text", style["color"]), ("bg", style["background-color"]), ("border", style["border-color"])]:
        put(f"{key}_color", f"lv_color_hex(0x{value[0]:06x})")
        put(f"{key}_opa", value[1])
    put("opa", style["opacity"])
    for side in ("top", "right", "bottom", "left"):
        put(f"pad_{side}", style[f"padding-{side}"])
    put("pad_row", style["row-gap"])
    put("pad_column", style["column-gap"])
    put("border_width", style["border-width"])
    put("radius", style["border-radius"])
    put("text_font", f"&lv_font_montserrat_{style['font-size']}")
    put("text_align", f"LV_TEXT_ALIGN_{style['text-align'].upper()}")
    put("flex_grow", style["flex-grow"])
    if node.kind == "container":
        direction = "ROW" if style["flex-direction"].startswith("row") else "COLUMN"
        flow = f"LV_FLEX_FLOW_{direction}"
        if style["flex-wrap"] == "wrap":
            flow += "_WRAP"
        if style["flex-direction"].endswith("reverse"):
            # LVGL provides enum bit flags for combined main/track reversal.
            flow = f"static_cast<lv_flex_flow_t>({flow} | LV_FLEX_REVERSE)"
        lines.append(f"  lv_obj_set_flex_flow({obj}, {flow});")
        align = {"flex-start": "START", "center": "CENTER", "flex-end": "END", "space-between": "SPACE_BETWEEN", "space-around": "SPACE_AROUND", "space-evenly": "SPACE_EVENLY"}
        lines.append(f"  lv_obj_set_flex_align({obj}, LV_FLEX_ALIGN_{align[style['justify-content']]}, LV_FLEX_ALIGN_{align[style['align-items']]}, LV_FLEX_ALIGN_{align[style['align-content']]});")
    if node.kind != "label" and style["overflow"] != "hidden":
        lines.append(f"  lv_obj_add_flag({obj}, LV_OBJ_FLAG_SCROLLABLE);")
        mode = "ON" if style["overflow"] == "scroll" else "AUTO"
        lines.append(f"  lv_obj_set_scrollbar_mode({obj}, LV_SCROLLBAR_MODE_{mode});")
    if node.hidden or style["display"] == "none":
        lines.append(f"  lv_obj_add_flag({obj}, LV_OBJ_FLAG_HIDDEN);")
    if node.disabled:
        lines.append(f"  lv_obj_add_state({obj}, LV_STATE_DISABLED);")
    return lines


def generate(document: Document):
    name = document.name
    header = f'''// Generated by esp-html-ui {__version__}. Edit the HTML/CSS source instead.
#pragma once
#include <EspHtmlUi.h>

namespace esphtml {{ namespace generated {{ namespace {name} {{
class Ui final : public ::esphtml::Screen {{
 public:
  bool create(lv_obj_t* parent);
  static constexpr int width() {{ return {document.width}; }}
  static constexpr int height() {{ return {document.height}; }}
}};
}} }} }}
'''
    lines = [f'// Generated by esp-html-ui {__version__}.', f'#include "{name}.h"', "",
             f"namespace esphtml {{ namespace generated {{ namespace {name} {{", "bool Ui::create(lv_obj_t* parent) {",
             f"  if (!begin(parent, {len(document.nodes)})) return false;"]
    for i, node in enumerate(document.nodes):
        obj = f"obj_{i}"
        if i == 0:
            lines.append(f"  lv_obj_t* {obj} = root();")
        else:
            constructor = {"container": "lv_obj_create", "label": "lv_label_create", "button": "lv_button_create"}[node.kind]
            lines.append(f"  lv_obj_t* {obj} = {constructor}(obj_{node.parent});")
            lines.append(f"  if (!{obj}) {{ clear(); return false; }}")
        lines.extend([f"  lv_obj_remove_style_all({obj});",
                      f"  lv_obj_remove_flag({obj}, static_cast<lv_obj_flag_t>(LV_OBJ_FLAG_SCROLLABLE | LV_OBJ_FLAG_CLICKABLE));",
                      f"  lv_obj_set_scrollbar_mode({obj}, LV_SCROLLBAR_MODE_OFF);"])
        lines.extend(styles(obj, node))
        text_obj = "nullptr"
        if node.kind in {"label", "button"}:
            text_obj = obj if node.kind == "label" else f"text_{i}"
            if node.kind == "button":
                lines.extend([f"  lv_obj_add_flag({obj}, LV_OBJ_FLAG_CLICKABLE);",
                              f"  lv_obj_t* {text_obj} = lv_label_create({obj});",
                              f"  if (!{text_obj}) {{ clear(); return false; }}",
                              f"  lv_obj_remove_style_all({text_obj});",
                              f"  lv_obj_remove_flag({text_obj}, LV_OBJ_FLAG_CLICKABLE);"])
                if node.style["width"][0] != "auto" or node.style["flex-grow"]:
                    lines.append(f"  lv_obj_set_width({text_obj}, lv_pct(100));")
                lines.append(f"  lv_obj_center({text_obj});")
            long_mode = "DOT" if node.style["text-overflow"] == "ellipsis" else "CLIP" if node.style["white-space"] in {"pre", "nowrap"} else "WRAP"
            lines.extend([f"  lv_label_set_long_mode({text_obj}, LV_LABEL_LONG_{long_mode});",
                          f"  lv_label_set_text({text_obj}, {cpp_string(node.text)});"])
        lines.append(f"  bind({i}, {cpp_string(node.id)}, {obj}, {text_obj}, {'true' if node.focusable else 'false'});")
    lines.extend(["  lv_obj_update_layout(root());", "  return true;", "}", "} } }", ""])
    manifest = {
        "compiler": __version__, "name": name, "lvgl": "9.4.0", "viewport": [document.width, document.height],
        "nodes": len(document.nodes), "ids": [n.id for n in document.nodes if n.id],
        "fonts": sorted({n.style["font-size"] for n in document.nodes}),
        "dependencies": {package: version(package) for package in ["html5lib", "tinycss2", "cssselect2", "six", "webencodings"]},
        "inputs": [{"path": Path(os.path.relpath(source, document.sources[0].parent)).as_posix(), "sha256": hashlib.sha256(source.read_bytes()).hexdigest()}
                   for source in document.sources],
        "assets": [],
    }
    return {f"{name}.h": header, f"{name}.cpp": "\n".join(lines),
            f"{name}.json": json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n"}
